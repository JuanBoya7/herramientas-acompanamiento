const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict'),fs=require('fs'),path=require('path');
const {pathToFileURL}=require('url');const root=path.resolve(__dirname,'..');
const out=path.join(root,'_respaldos/2026-10-07-prioridad-en-sesion/qa');
let browser;
(async()=>{
 browser=await chromium.launch({channel:'msedge',headless:true});
 const ctx=await browser.newContext({viewport:{width:1600,height:1000}});const p=await ctx.newPage();
 const errors=[];p.on('pageerror',e=>errors.push(e.message));let checks=[];
 const load=async n=>{await p.goto(pathToFileURL(path.join(root,n+'.html')).href);await p.waitForTimeout(120);};
 await load('met-hojas-en-el-arroyo');
 assert.equal(await p.locator('#btnEnganche').isVisible(),false);
 await p.locator('#pensamientos .chip').first().click();await p.locator('#btnArrancar').click();
 await p.waitForTimeout(3500);assert.ok(await p.locator('#arroyo text').count()>0);
 await p.screenshot({path:path.join(out,'arroyo-en-practica.png')});
 await p.setViewportSize({width:390,height:900});
 await p.screenshot({path:path.join(out,'arroyo-en-practica-movil.png')});
 await p.getByRole('button',{name:'Terminar y conversar',exact:true}).click();
 assert.equal(await p.locator('#cajaPregunta').isVisible(),true);
 assert.equal(await p.locator('#btnArrancar').isEnabled(),true);
 await p.reload();assert.equal(await p.locator('#pensamientos .activa').count(),1);
 assert.equal(await p.locator('#btnEnganche').isVisible(),false);
 await p.getByText('Duración, corriente y registro de enganches',{exact:true}).click();
 await p.locator('#cMarcar').click();assert.equal(await p.locator('#btnEnganche').isVisible(),true);
 checks.push('Arroyo: práctica, cierre libre, legibilidad móvil, persistencia y enganche opcional');
 await p.setViewportSize({width:1600,height:1000});await load('met-la-cuerda');
 await p.locator('#monstruo .chip').first().click();await p.locator('#btnArrancar').click();
 await p.locator('#btnJalar').click();await p.locator('#btnSoltar').click();await p.waitForTimeout(450);
 assert.equal(await p.locator('#bocadillo').isVisible(),true);
 assert.equal(await p.locator('#btnRetomar').isVisible(),true);
 assert.equal(await p.locator('#tira image').count(),1);
 await p.evaluate(()=>window.scrollTo(0,0));await p.screenshot({path:path.join(out,'cuerda-manos-libres.png')});
 checks.push('Cuerda: jalar, soltar, manos libres y monstruo persistente');
 await load('act-matriz');await p.locator('#importa .chip').first().click();
 await p.locator('.sesion-apoyo > summary').first().click();
 assert.equal(await p.locator('#matriz').isVisible(),true);
 await p.reload();assert.equal(await p.locator('#importa .activa').count(),1);
 checks.push('Matriz: abrir un complemento conserva el mapa; elecciones restauradas');
 await load('fortalezas-del-caracter');
 await p.locator('#virtudes [data-n]').first().click();
 assert.equal(await p.locator('#casillas .llena').count(),1);
 assert.equal(await p.locator('#perfil').isVisible(),false);
 await p.locator('.sesion-apoyo > summary').first().click();
 assert.equal(await p.locator('#casillas .llena').isVisible(),true);
 checks.push('Fortalezas: selección activa y perfil opcional');
 await load('met-jardin-de-valores');await p.locator('#semillero .pieza').first().click();
 await p.locator('#pasoRaiz h2').click();assert.equal(await p.locator('#raices').isVisible(),true);
 await p.locator('#raices .raizChip:not(.mas)').first().click();await p.locator('#pasoRiego h2').click();
 assert.equal(await p.locator('#riegos input[type=range]').count(),1);
 checks.push('Jardín: sembrar, enraizar y regar conservados');
 // Las advertencias de sueño preceden a la calculadora y no dependen de abrir un apoyo.
 await load('tcc-ventana-de-sueno');assert.equal(await p.locator('#antecedentes').isVisible(),true);
 assert.ok(await p.locator('#antecedentes').evaluate(e=>e.getBoundingClientRect().top)<await p.locator('#tib').evaluate(e=>e.getBoundingClientRect().top));
 await load('crisis-plan-de-seguridad');assert.equal(await p.locator('.sesion-principal section:visible').count(),7);
 checks.push('Precauciones de sueño y componentes del plan de seguridad accesibles');
 assert.deepEqual(errors,[]);fs.writeFileSync(path.join(out,'interacciones.json'),JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks,errors}));await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();});
